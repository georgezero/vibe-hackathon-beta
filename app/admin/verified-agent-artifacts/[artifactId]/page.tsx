import Link from "next/link";
import { cookies } from "next/headers";
import { Nav } from "@/components/Nav";
import { VerifiedArtifactControls } from "@/components/viby/VerifiedArtifactControls";
import { VibyArtifactSeal } from "@/components/viby/VibyArtifactSeal";
import { requireAdminSession } from "@/lib/admin-session";
import { applicationHeaderAccount } from "@/lib/application-account-display";
import {
  VERIFIED_ARTIFACT_COOKIE,
  artifactTypeConfig,
  decodeVerifiedArtifact,
  formatVerifiedArtifactExport,
} from "@/lib/verifiedArtifacts";

export const dynamic = "force-dynamic";

type Props = {
  params: Promise<{ artifactId: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
};

function first(value: string | string[] | undefined) {
  return Array.isArray(value) ? value[0] : value;
}

export default async function VerifiedArtifactDetailPage({ params, searchParams }: Props) {
  const adminSession = await requireAdminSession();
  const { artifactId } = await params;
  const query = await searchParams;
  const queryToken = first(query.artifact);
  const cookieToken = (await cookies()).get(VERIFIED_ARTIFACT_COOKIE)?.value;
  const artifactToken = queryToken ?? cookieToken;
  const artifact = artifactToken ? decodeVerifiedArtifact(artifactToken) : null;
  const tokenMismatch = Boolean(artifact && artifact.artifactId !== artifactId);
  const validArtifact = artifact && !tokenMismatch ? artifact : null;
  const exportText = validArtifact ? formatVerifiedArtifactExport(validArtifact) : null;

  return (
    <div className="flex min-h-screen flex-col">
      <Nav authenticatedAccount={applicationHeaderAccount(adminSession)} />
      <main className="flex-1 px-4 py-10">
        <div style={{ width: "100%", maxWidth: 940, margin: "0 auto" }}>
          <Link href="/admin/verified-agent-artifacts" style={{ color: "var(--color-accent)", fontSize: "0.875rem", textDecoration: "none" }}>
            Back to verified artifacts
          </Link>

          <section className="card" style={{ padding: "1.5rem", marginTop: "1rem" }}>
            <div className="badge badge-success" style={{ marginBottom: "0.75rem" }}>
              Verified Artifact
            </div>
            <h1
              style={{
                fontFamily: "var(--font-headline)",
                fontSize: "1.85rem",
                fontWeight: 900,
                letterSpacing: "-0.035em",
                color: "var(--color-fg)",
                marginBottom: "0.5rem",
              }}
            >
              Artifact Details
            </h1>
            <p style={{ color: "var(--color-muted)", fontSize: "0.92rem", lineHeight: 1.6, maxWidth: 680 }}>
              Full content, Viby identity seal, and technical verification metadata for a session-scoped artifact.
            </p>
          </section>

          {!validArtifact && (
            <section className="card" style={{ padding: "1.25rem", marginTop: "1rem" }}>
              <h2 style={{ color: "var(--color-fg)", fontWeight: 850, fontSize: "1.1rem", marginBottom: "0.35rem" }}>
                Artifact unavailable
              </h2>
              <p style={{ color: "var(--color-muted)", fontSize: "0.9rem", lineHeight: 1.55 }}>
                This artifact is not available in the current browser session, or the signed artifact payload does not match this detail URL.
              </p>
            </section>
          )}

          {validArtifact && (
            <section className="grid gap-4" style={{ marginTop: "1rem" }}>
              <div className="card" style={{ padding: "1.25rem" }}>
                <div className="flex flex-wrap gap-2" style={{ marginBottom: "0.875rem" }}>
                  <span className="badge badge-success">Verified artifact</span>
                  <span className="badge badge-default">{artifactTypeConfig(validArtifact.artifactType).label}</span>
                  <span className="badge badge-default">Actor type: agent</span>
                </div>
                <h2 style={{ color: "var(--color-fg)", fontWeight: 900, fontSize: "1.45rem", marginBottom: "0.35rem" }}>
                  {validArtifact.projectTitle}
                </h2>
                <p style={{ color: "var(--color-muted)", fontSize: "0.875rem", marginBottom: "1rem" }}>
                  Generated by {validArtifact.generatedByAgentName}, owned by {validArtifact.ownerDisplayName}.
                </p>
                <div
                  style={{
                    border: "1px solid var(--color-border)",
                    borderRadius: 14,
                    padding: "1rem",
                    background: "var(--color-surface-2)",
                    color: "var(--color-fg)",
                    lineHeight: 1.65,
                    marginBottom: "1rem",
                  }}
                >
                  {validArtifact.content}
                </div>
                <VibyArtifactSeal artifact={validArtifact} />
                <div style={{ marginTop: "1rem" }}>
                  <VerifiedArtifactControls
                    artifact={validArtifact}
                    artifactToken={artifactToken}
                    exportText={exportText}
                  />
                </div>
              </div>

              <details className="card" style={{ padding: "1rem" }}>
                <summary style={{ color: "var(--color-muted)", fontFamily: "var(--font-mono)", fontSize: "0.75rem", cursor: "pointer" }}>
                  Technical details
                </summary>
                <div className="grid gap-2 sm:grid-cols-2" style={{ marginTop: "0.75rem" }}>
                  <Info label="Artifact ID" value={validArtifact.artifactId} mono />
                  <Info label="Full SHA-256" value={`sha256:${validArtifact.sha256}`} mono />
                  <Info label="Full timestamp" value={new Date(validArtifact.createdAt).toISOString()} mono />
                  <Info label="Actor type" value={validArtifact.signature.actorType} mono />
                  <Info label="Issued time" value={validArtifact.signature.issuedAt ?? "unknown"} mono />
                  <Info label="Expires time" value={validArtifact.signature.expiresAt ?? "unknown"} mono />
                </div>
              </details>
            </section>
          )}
        </div>
      </main>
    </div>
  );
}

function Info({ label, value, mono }: { label: string; value: string; mono?: boolean }) {
  return (
    <div className="card" style={{ padding: "0.75rem" }}>
      <div style={{ color: "var(--color-subtle)", fontSize: "0.7rem", textTransform: "uppercase", letterSpacing: "0.08em", fontFamily: "var(--font-mono)" }}>
        {label}
      </div>
      <div style={{ color: "var(--color-fg)", fontSize: "0.825rem", fontFamily: mono ? "var(--font-mono)" : undefined, overflowWrap: "anywhere" }}>
        {value}
      </div>
    </div>
  );
}
